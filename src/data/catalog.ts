const slugify = (s: string) =>
  s
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const DEFAULT_COLORS = ["#f5f1e8", "#1a1a1a", "#2a5d3e", "#c97a4a"];

let __id = 0;
let __ts = Date.now();

const makeProducts = (
  baseName: string,
  catSlug: string,
  subSlug: string,
  image: string,
  tier: Tier | undefined,
  count = 3,
): CatalogProduct[] => {
  const out: CatalogProduct[] = [];
  for (let i = 1; i <= count; i++) {
    __id++;
    __ts += 1000;
    const priceBase = tier === "premium" ? 540 : 280;
    const price = priceBase + i * 30;
    out.push({
      id: `c${__id}`,
      code: `ARR-${catSlug.substring(0, 3).toUpperCase()}-${String(__id).padStart(4, "0")}`,

      name: count > 1 ? `${baseName} — Style ${i}` : baseName,
      categorySlug: catSlug,
      subSlug,
      tier,
      fabric: baseName,
      gsm: tier === "premium" ? "Premium" : "Standard",
      moq: 20,
      price: `₹${price}`,
      samplePrice: price,
      image,
      gallery: [image, image, image, image, image, image],
      colors: DEFAULT_COLORS,
      description: `${baseName} — engineered for bulk corporate and event orders. Pre-shrunk, bio-washed, made in-house with strict QC.`,
      material: baseName,
      isNew: i === 1,
      addedAt: __ts,
    });
  }
  return out;
};

type SubInput =
  | string
  | {
      name: string;
      image: string;
      banner?: string;
    };

const makeSubs = (
  catSlug: string,
  defaultImage: string,
  tier: Tier | undefined,
  names: SubInput[],
  perSub = 3,
): Subcategory[] =>
  names.map((item) => {
    const name = typeof item === "string" ? item : item.name;
    const image = typeof item === "string" ? defaultImage : item.image;
    const banner = typeof item === "string" ? undefined : item.banner;
    const slug = slugify(name);

    return {
      slug,
      name,
      tier,
      image,
      banner,
      products: makeProducts(name, catSlug, slug, image, tier, perSub),
    };
  });

